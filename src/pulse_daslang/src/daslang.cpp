// NEED_MODULE/NEED_ALL_DEFAULT_MODULES must be at global scope; they emit
// references to the global register_* functions generated by REGISTER_MODULE.
void need_das_modules()
{
    NEED_ALL_DEFAULT_MODULES;
    NEED_MODULE(ModuleFlecs);
    NEED_MODULE(ModuleCGPU);
    NEED_MODULE(ModulePulse);
}

